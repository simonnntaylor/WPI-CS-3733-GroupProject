-- REFERENCE ONLY: this file is NOT run anywhere.
--
-- The real database is DynamoDB, and its tables are created by CDK in
-- lib/backend-stack.ts. This file documents what each table holds, so the
-- team has one place to look. Keep it in sync when the tables change.
--
-- DynamoDB basics:
-- * Only the KEY fields are fixed when a table is created. Every other field
--   below is a convention our Lambdas follow, not something DynamoDB enforces.
-- * Partition key (PK): how a row is found. Sort key (SK): lets one partition
--   hold many rows, sorted. PK + SK together must be unique.
-- * No joins, foreign keys, cascades, or unique constraints besides the key.
--   Lambdas must keep related tables consistent themselves.
-- * Logins (usernames/passwords) live in AWS Cognito, not in these tables.
--
-- Settings for every table: on-demand billing, deleted on `cdk destroy`,
-- names generated by CDK (printed as outputs after `cdk deploy`).
-- =============================================================================


-- -----------------------------------------------------------------------------
-- Organizations: the site's single organization
--   PK  username      string   same as its Cognito username
--       name          string   display name
-- -----------------------------------------------------------------------------

-- -----------------------------------------------------------------------------
-- DonationCenters
--   PK  name          string   unique; same as the center's Cognito username
--       streetAddress string   e.g. "100 Institute Rd, Worcester, MA 01609"
--       latitude      number
--       longitude     number
--       totalItems    number   running total, updated whenever Inventory changes
--       totalValue    number   running total (sum of price * quantity)
-- -----------------------------------------------------------------------------

-- -----------------------------------------------------------------------------
-- Categories
--   PK  categoryName  string   e.g. "Clothing"
-- -----------------------------------------------------------------------------

-- -----------------------------------------------------------------------------
-- CategoryItems: items in each category with an allowed price range
--   PK  categoryName  string   e.g. "Clothing"
--   SK  itemName      string   e.g. "Shoes" (permanent: rename = remove + add)
--       lowPrice      number
--       highPrice     number
-- -----------------------------------------------------------------------------

-- -----------------------------------------------------------------------------
-- Inventory: what each center has. One row per donated line; the same item
-- name can appear in several rows with different donor-set prices.
--   PK  centerName    string   -> DonationCenters.name
--   SK  itemId        string   random ID
--       name          string   e.g. "Shoes"
--       category      string   -> Categories.categoryName
--       price         number   set by the donor, per unit
--       quantity      number
-- -----------------------------------------------------------------------------

-- -----------------------------------------------------------------------------
-- WishList: which categories each center wants
--   PK  centerName    string   -> DonationCenters.name
--   SK  categoryName  string   -> Categories.categoryName
--       streetAddress string   copy of the center's address, for search results
--
--   Index "byCategory" (for /searchDonationCenters):
--   PK  categoryName  ->  SK  centerName
-- -----------------------------------------------------------------------------

-- -----------------------------------------------------------------------------
-- Boxes: a donor's box for one center
--   PK  boxId         string   random, e.g. "box-7f3a9c2e"
--       centerName    string   -> DonationCenters.name
--       status        string   "open" while packing, "donated" when complete
--       items         list     [{ name, category, price, quantity }, ...]
-- -----------------------------------------------------------------------------
